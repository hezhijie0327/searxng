/** locales the theme translates itself; every other locale falls back to EN */
const THEME_STRINGS: Record<string, Record<string, string>> = {
  en: EN,
  "zh-CN": ZH_CN,
};

function themeLocaleTag(locale: string): string {
  const tag = locale.toLowerCase();
  // Simplified Chinese only (zh-CN, zh-Hans-CN, zh); Traditional stays English
  if (tag.startsWith("zh") && !tag.includes("hant")) {
    return "zh-CN";
  }
  return "en";
}

export const I18nContext = createContext<string>("en");

export function useT(): Translate {
  const locale = useContext(I18nContext);
  const theme = THEME_STRINGS[themeLocaleTag(locale)] ?? EN;
  return (key: string) => theme[key] ?? EN[key] ?? key;
}
